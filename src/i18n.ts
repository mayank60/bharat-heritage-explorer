/**
 * Parameter interpolation engine: replaces '{key}' with params[key]
 */
export function interpolateParams(
  template: string,
  params?: Record<string, string | number>
): string {
  if (!params || !template) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) => {
    return params[key] !== undefined ? String(params[key]) : match;
  });
}

/**
 * Universal safe translation function with comprehensive fallback hierarchy:
 * 1. Target language exact key
 * 2. English ('en') fallback
 * 3. Fallback string if provided
 * 4. Human-readable key fallback
 *
 * Guaranteed NEVER to throw or default wrongly to Hindi when English is active.
 */
export function t(
  key: string,
  lang: LanguageKey = 'en',
  params?: Record<string, string | number>,
  fallback?: string
): string {
  if (!key) return fallback || '';

  try {
    const langDict = TRANSLATIONS[lang];
    let translation = langDict ? langDict[key] : undefined;

    // Fallback hierarchy: Target Language -> English ('en') -> Provided fallback -> Key
    if (!translation && lang !== 'en') {
      const enDict = TRANSLATIONS.en;
      translation = enDict ? enDict[key] : undefined;
    }

    if (!translation) {
      if (fallback !== undefined) {
        return interpolateParams(fallback, params);
      }
      // Return humanized key fallback instead of crashing
      return interpolateParams(key.replace(/_/g, ' '), params);
    }

    return interpolateParams(translation, params);
  } catch (err) {
    console.warn(`[i18n] Error translating key '${key}' for language '${lang}':`, err);
    return fallback || key;
  }
}

/**
 * Helper to obtain the full translation bundle with safe Proxy fallback
 */
export function getTranslationBundle(lang: LanguageKey = 'en'): Record<string, string> {
  const current = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return new Proxy(current, {
    get(target, prop: string) {
      if (prop in target) {
        return target[prop];
      }
      if (prop in TRANSLATIONS.en) {
        return TRANSLATIONS.en[prop];
      }
      return prop.replace(/_/g, ' ');
    }
  });
}
